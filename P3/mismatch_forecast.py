"""Given-input offline simulation forecasts; future measured outputs are targets only.

The matched initial simulator state and common future environmental sequence
isolate model mismatch. They are not deployable measurements or network inputs.
Forecast history after initialization is generated by the model itself.
"""
import torch
from .mismatch_dynamics import HybridDynamics
from .mismatch_runtime import HybridTransitionGraph
from P2.hover_bptt.onboard import NominalVehicle,Sensors
from P2.hover_bptt.functional import FunctionalHistory,DifferentiableAerodynamics
from P2.hover_bptt.environment import settings


def initial_history(obs,configuration,stage):
    device=str(obs.device);n=len(obs);vehicle=NominalVehicle(configuration,device)
    aero=DifferentiableAerodynamics(configuration['airframe'],configuration['aero'],device)
    history=FunctionalHistory(vehicle,n,.01,stage['sensors'].get('motion_features'),aero,stage['sensors'].get('angular_prediction_mode','interval_motor'))
    history.previous_rate=obs[:,4:7]*4;history.previous_speed=obs[:,10:14]*vehicle.max_speed;history.valid=torch.ones(n,dtype=torch.bool,device=device);history.cached=obs.clone()
    history.height.height=5-obs[:,18]*2;history.height.speed=obs[:,19]*3;history.height.valid=history.valid.clone()
    if history.motion:
        history.motion.velocity=obs[:,28:30]*3;history.motion.position=obs[:,30:32]*5;history.motion.cached=obs[:,26:35].clone()
    return history


@torch.no_grad()
def predict_window(net,model,configuration,batch,learned=True,stage=None):
    stage=settings() if stage is None else stage;device=str(batch['initial_state'].device)
    state=batch['initial_state'].clone();obs=batch['obs'].clone();hidden=batch['hidden'][None].clone()
    history=initial_history(obs,configuration,stage);force=batch['initial_packet'][:,7:10].clone()
    hybrid=HybridDynamics(model);zero=state.new_zeros(len(state),7)
    first_command=torch.cat((batch['commands'][:,0],state.new_zeros(len(state),2)),-1)
    first_wind=batch['wind'][:,0,None].expand(-1,model.substeps,-1).contiguous()
    transition=HybridTransitionGraph(hybrid.control,(state,first_command,first_wind,zero),backward=False) if device.startswith('cuda') else hybrid.control
    states=[];packets=[];corrections=[]
    for index in range(batch['commands'].shape[1]):
        motors=batch['commands'][:,index];command=torch.cat((motors,torch.zeros_like(motors[:,:2])),-1)
        correction=net(obs,hidden[0],batch['context'],motors) if learned else zero
        winds=batch['wind'][:,index,None].expand(-1,model.substeps,-1).contiguous()
        state=transition(state,command,winds,correction)
        endpoint=batch['end_wind'][:,index] if 'end_wind' in batch else batch['wind'][:,min(index+1,batch['wind'].shape[1]-1)]
        specific=hybrid.loads(state,endpoint,correction)[2]
        force=force+stage['sensors']['specific_force_filter_alpha']*(specific-force)
        q=state[:,6:10]*torch.where(state[:,6:7]<0,-1.,1.)
        packet=Sensors(q,state[:,10:13],force,state[:,13:17],-state[:,2])
        states.append(state.clone());packets.append(torch.cat((q,packet.gyro,force,packet.motor_speed,packet.baro_height[:,None]),-1));corrections.append(correction.clone())
        obs=history.update(packet,motors)
        if learned:_,hidden=net.encode(obs,hidden)
    return dict(states=torch.stack(states,1),packets=torch.stack(packets,1),corrections=torch.stack(corrections,1))


def sensor_errors(predicted,target):
    q=predicted[...,:4];reference=target[...,:4];aligned=q*torch.where((q*reference).sum(-1,keepdim=True)<0,-1.,1.)
    return dict(attitude=2*(aligned-reference)[...,1:],gyro=predicted[...,4:7]-target[...,4:7],specific_force=predicted[...,7:10]-target[...,7:10],rpm=predicted[...,10:14]-target[...,10:14],height=predicted[...,14:15]-target[...,14:15])
